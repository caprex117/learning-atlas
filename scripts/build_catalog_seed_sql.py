"""Build the owner-scoped, repeatable SQL Editor loader from the validated catalog."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from atlas.catalog_seed import read_seed
from atlas.catalog_models import Opportunity
from atlas.models import canonical_hash


def build():
    seed = read_seed()
    payload = {**seed, 'opportunities': [dict(identity_key=i.identity(), content_hash=canonical_hash(i.model_dump(mode='json')),
                   payload=i.model_dump(mode='json')) for i in map(Opportunity.model_validate, seed['opportunities'])]}
    encoded = json.dumps(payload, ensure_ascii=False, indent=2)
    if '$atlas_catalog_data$' in encoded:
        raise ValueError('SQL delimiter collision')
    return HEADER + encoded + FOOTER


HEADER = """-- Generated by scripts/build_catalog_seed_sql.py. DATA ONLY; requires migrations 001 and 002.
-- Run the WHOLE file in Supabase SQL Editor. Repeat execution is safe.
-- If exactly one Learning Atlas profile exists, no editing is needed.
-- With multiple profiles, replace NULL below with your Authentication user UUID in single quotes.
-- Does not create users, disable RLS, change grants, or record learning activity.
begin;
do $atlas_catalog_load$
declare
 target_user uuid := NULL;
 seed jsonb := $atlas_catalog_data$
"""

FOOTER = """
$atlas_catalog_data$::jsonb;
 rev bigint; run_id uuid := gen_random_uuid(); catalog_oid uuid;
 candidate jsonb; full_item jsonb; old_item public.opportunities%rowtype;
 child record; before_payload jsonb; changed_fields jsonb; changes jsonb := '[]'::jsonb;
 row_data jsonb; added integer := 0; changed integer := 0; total integer;
 current_stamp timestamptz := clock_timestamp(); summary jsonb;
 saved_sub text := current_setting('request.jwt.claim.sub', true);
 saved_claims text := current_setting('request.jwt.claims', true);
begin
 if target_user is null then
   if (select count(*) from public.profiles) <> 1 then
     raise exception 'CATALOG_OWNER_REQUIRED: set target_user to your user UUID; exactly one Learning Atlas profile is required for automatic selection.';
   end if;
   select user_id into target_user from public.profiles;
 end if;
 select revision into rev from public.profiles where user_id=target_user for update;
 if not found then raise exception 'CATALOG_PROFILE_MISSING: sign in to Learning Atlas first.'; end if;
 total := jsonb_array_length(seed->'opportunities');
 for candidate in select value from jsonb_array_elements(seed->'opportunities') loop
   full_item := candidate->'payload';
   select * into old_item from public.opportunities o
     where o.user_id=target_user and o.identity_key=candidate->>'identity_key';
   if found then
     if old_item.origin <> 'curated' or old_item.checked_at > (seed->>'checked_at')::timestamptz
        or old_item.content_hash=candidate->>'content_hash' then continue; end if;
     catalog_oid := old_item.id;
     changed := changed+1;
   else
     catalog_oid := gen_random_uuid();
     added := added+1;
   end if;
   row_data := (full_item - 'sources' - 'components') || jsonb_build_object(
     'id',catalog_oid, 'identity_key',candidate->>'identity_key', 'content_hash',candidate->>'content_hash',
     'checked_at',seed->>'checked_at', 'origin','curated', 'research_focus',seed->'focus'->>'focus');
   changes := changes || jsonb_build_array(jsonb_build_object('op','upsert','table','opportunities','row',row_data));
   select v.payload into before_payload from public.opportunity_versions v
     where v.user_id=target_user and v.opportunity_id=catalog_oid order by v.checked_at desc limit 1;
   select coalesce(jsonb_agg(key order by key),'[]'::jsonb) into changed_fields
     from jsonb_each(full_item) where value is distinct from coalesce(before_payload,'{}'::jsonb)->key;
   row_data := jsonb_build_object('id',gen_random_uuid(),'opportunity_id',catalog_oid,'run_id',run_id,
       'payload',full_item,'content_hash',candidate->>'content_hash','changed_fields',changed_fields,'checked_at',seed->>'checked_at');
   changes := changes || jsonb_build_array(jsonb_build_object('op','upsert','table','opportunity_versions','row',row_data));
   for child in select s.id,'opportunity_sources' as tab from public.opportunity_sources s
      where s.user_id=target_user and s.opportunity_id=catalog_oid
      union all select p.id,'pack_components' from public.pack_components p
      where p.user_id=target_user and p.opportunity_id=catalog_oid loop
     changes := changes || jsonb_build_array(jsonb_build_object('op','delete','table',child.tab,'id',child.id));
   end loop;
   for child in select value from jsonb_array_elements(full_item->'sources') loop
     row_data := child.value || jsonb_build_object('id',gen_random_uuid(),'opportunity_id',catalog_oid,'checked_at',seed->>'checked_at');
     changes := changes || jsonb_build_array(jsonb_build_object('op','upsert','table','opportunity_sources','row',row_data));
   end loop;
   for child in select value,ordinality from jsonb_array_elements(full_item->'components') with ordinality loop
     row_data := child.value || jsonb_build_object('id',gen_random_uuid(),'opportunity_id',catalog_oid,'sort_order',child.ordinality-1);
     changes := changes || jsonb_build_array(jsonb_build_object('op','upsert','table','pack_components','row',row_data));
   end loop;
 end loop;
 if added+changed=0 and exists(select 1 from public.discovery_runs r where r.user_id=target_user
      and r.origin='seed' and r.status='completed' and r.details->>'seed_revision'=seed->>'seed_revision') then
   raise notice 'Selection already loaded; no changes.';
   return;
 end if;
 summary := jsonb_build_object('added',added,'changed',changed,'checked',total,'preserved',total-added-changed);
 row_data := jsonb_build_object('id',run_id,'status','completed','origin','seed','started_at',current_stamp,
   'finished_at',current_stamp,'model_id','curated','focus_snapshot',seed->'focus','error_message','',
   'details',summary || jsonb_build_object('seed_revision',seed->>'seed_revision','seed_sequence',coalesce(seed->'seed_sequence','0'::jsonb),'rankings',seed->'rankings',
              'research_checked_at',seed->>'checked_at','method',seed->>'note'));
 changes := jsonb_build_array(jsonb_build_object('op','upsert','table','discovery_runs','row',row_data)) || changes;
 perform set_config('request.jwt.claim.sub',target_user::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',target_user,'role','authenticated')::text,true);
 perform public.atlas_apply(gen_random_uuid(),rev,
       jsonb_build_object('action','catalog_seed','seed_revision',seed->>'seed_revision'),changes,summary,null);
 perform set_config('request.jwt.claim.sub',coalesce(saved_sub,''),true);
 perform set_config('request.jwt.claims',coalesce(saved_claims,''),true);
 raise notice 'Catalog selection: % added, % enriched, % preserved.',added,changed,total-added-changed;
end;
$atlas_catalog_load$;
commit;
"""

if __name__ == '__main__':
    target = ROOT/f"supabase/seeds/learning_catalog_{len(read_seed()['opportunities'])}.sql"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(build(), encoding='utf-8')
    print('Generated owner-scoped catalog data loader.')
